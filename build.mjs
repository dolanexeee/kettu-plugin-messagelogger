// Build script — assembles the two installable plugin files from the
// single shared core (src/core.js) plus one format adapter each, and
// writes the manifests (the Vendetta manifest carries the sha256 of
// index.js, which Kettu uses to detect updates).
//
//   node build.mjs
//
// Outputs (committed to the repo):
//   index.js                          Vendetta format (primary install)
//   manifest.json                     Vendetta polymanifest (hash = sha256)
//   repo.json                         Bunny plugin repository index
//   builds/messagelogger/index.js     Bunny-native format (secondary install)
//   builds/messagelogger/manifest.json
//
// The two index.js files contain identical logic by construction — the
// only difference is the adapter (vendetta vs bunny API object).

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)));
const read = (p) => readFileSync(join(root, p), "utf8");
const write = (p, s) => { writeFileSync(join(root, p), s); console.log("wrote", p, s.length + " bytes"); };

const VERSION = "1.0.0";
const core = read("src/core.js");
const vendettaAdapter = read("src/vendetta-adapter.js");
const bunnyAdapter = read("src/bunny-adapter.js");

const header = (format) =>
`/* Message Logger v${VERSION} — Kettu plugin (${format}).
 * GENERATED by build.mjs from src/core.js + a format adapter — do not edit
 * by hand; edit the sources and run: node build.mjs
 * Install: paste https://dolanexeee.github.io/kettu-plugin-messagelogger/
 * into Kettu → Settings → Plugins → Install a plugin.
 */\n`;

// --- Vendetta format (primary) -------------------------------------------
// Kettu evaluates this file as: vendetta => { return <file> }
// (src/core/vendetta/plugins.ts evalPlugin). The file must therefore be a
// single expression whose value is the plugin object (or { default: ... }).
// CRITICAL: the file must START with the IIFE — no leading comment.
// `return` followed by a multi-line comment (which contains a line
// terminator) makes JS insert a semicolon after `return`, so the eval
// returns undefined and the plugin silently never loads. (Verified in
// Node: all five sibling plugins in kettu-plugins/ have this bug — their
// leading /* ... */ header makes evalPlugin return undefined.)
// The header comment therefore goes INSIDE the IIFE, after the opening
// brace, where line terminators are harmless.
const vendettaJs =
`(function (vendetta) {
${header("Vendetta format")}
"use strict";
${core}
${vendettaAdapter}
return { default: {
    onLoad: function () { inst.start(); },
    onUnload: function () { inst.stop(); },
    settings: inst.SettingsComponent
} };
})(vendetta);
`;
write("index.js", vendettaJs);

const hash = createHash("sha256").update(vendettaJs).digest("hex");
write("manifest.json", JSON.stringify({
    name: "Message Logger",
    description: "Keeps deleted and edited messages visible — deleted messages stay in place in the chat, edits keep their history. View the log in the plugin settings.",
    authors: [{ name: "dolanexeee" }],
    main: "index.js",
    hash
}, null, 2) + "\n");

// --- Bunny-native format (secondary) --------------------------------------
// Kettu wraps this file as: (bunny,definePlugin)=>{ <file>; return plugin?.default ?? plugin; }
// (src/lib/addons/plugins/index.ts startPlugin). The file must define
// `var plugin = { default: { start, stop, SettingsComponent } }`.
const bunnyJs = header("Bunny-native format") +
`var plugin = (function (bunny) {
${core}
${bunnyAdapter}
return { default: {
    start: function () { inst.start(); },
    stop: function () { inst.stop(); },
    SettingsComponent: inst.SettingsComponent
} };
})(bunny);
`;
mkdirSync(join(root, "builds/messagelogger"), { recursive: true });
write("builds/messagelogger/index.js", bunnyJs);

write("builds/messagelogger/manifest.json", JSON.stringify({
    id: "messagelogger",
    spec: 3,
    type: "plugin",
    version: VERSION,
    display: {
        name: "Message Logger",
        description: "Keeps deleted and edited messages visible — deleted messages stay in place in the chat, edits keep their history. View the log in the plugin settings.",
        authors: [{ name: "dolanexeee" }]
    },
    main: "index.js"
}, null, 2) + "\n");

write("repo.json", JSON.stringify({
    $meta: {
        name: "Message Logger",
        description: "Kettu plugin repository for Message Logger (deleted + edited messages)."
    },
    messagelogger: { version: VERSION }
}, null, 2) + "\n");

console.log("manifest hash:", hash);
